function C = instantaneous_cost(x,yEff,uEff,A,L,p,mode)
%INSTANTANEOUS_COST Common cost definition used by dynamics and Exp08.
C = yEff*(p.CR*(0.5+0.5*uEff^2)+p.f*x*p.CfpF) ...
    + p.c*p.costLabel ...
    + p.costBacklog*A ...
    + p.costProvenance*L ...
    + p.antiE*p.costAntiEvasion;
if mode.costDynamic, C = C + p.costDynamicSystem; end
if mode.costFixed, C = C + p.costFixedSystem; end
if mode.costPolicy, C = C + p.costPolicyImplementation; end
end
