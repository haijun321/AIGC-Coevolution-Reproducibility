function outputDir = RUN_THEORY_P1_IZ_STABILITY_AUDIT_V10_SR_V2(runMode)
%RUN_THEORY_P1_IZ_STABILITY_AUDIT_V10
% ========================================================================
% Numerical code-to-theory audit for the reduced (I,z) feedback argument.
%
% Reduced-theory idea
%   Hold the remaining states locally fixed. The core feedback is expected
%   to have the sign structure
%
%       partial(dot I)/partial z < 0     (more vigilant users suppress risk)
%       partial(dot z)/partial I > 0     (more risk raises vigilance incentive)
%
%   For the 2x2 local Jacobian
%
%       J_IZ = [ F_I  F_z
%                G_I  G_z ],
%
%   trace(J_IZ)<0 and det(J_IZ)>0 imply local asymptotic stability of the
%   frozen-background reduced subsystem. This does NOT claim that the full
%   10-D system is always stable. It is designed to support the manuscript
%   statement that the direct risk-vigilance loop is locally stabilizing,
%   while persistent oscillations can be generated by additional slow and
%   adaptive states (u,A,L,M,E).
%
% What the script does
%   1) Loads the active V10 RHS and R1 parameter set.
%   2) Obtains a long-run reference state from the active full model.
%   3) Freezes all states except I and z.
%   4) Computes finite-difference partial derivatives directly from
%      aigc.model_rhs -- no duplicate hand-coded RHS is introduced.
%   5) Audits the sign pattern and 2-D Hurwitz conditions at the reference
%      state and on a local I-z grid.
%
% DIRECT RUN
%   RUN_THEORY_P1_IZ_STABILITY_AUDIT_V10_SR_V2('preview')
%   RUN_THEORY_P1_IZ_STABILITY_AUDIT_V10_SR_V2('full')
% ========================================================================

if nargin<1 || isempty(runMode), runMode='full'; end
runMode=lower(char(runMode));
if ~ismember(runMode,{'preview','quick','full'}), error('runMode must be preview/quick/full.'); end
clc; close all force;

CFG=struct();
CFG.RUN_MODE=runMode;
CFG.RUN_TAG='paper_v1';
CFG.HORIZONS=[600 1200 2400];
CFG.TAIL_FRACTION=0.40;
CFG.FD_STEP=1e-6;
CFG.SPAN_I=0.15;
CFG.SPAN_Z=0.15;
CFG.INTERIOR_MARGIN=1e-4;
CFG.SHOW_FIGURES=true;
switch runMode
    case 'preview', CFG.GRID_N=21; CFG.REFERENCE_HORIZON=600;
    case 'quick',   CFG.GRID_N=31; CFG.REFERENCE_HORIZON=1200;
    case 'full',    CFG.GRID_N=51; CFG.REFERENCE_HORIZON=2400;
end

fprintf('\n====================================================================\n');
fprintf(' Theory-P1 | REDUCED (I,z) LOCAL-STABILITY AUDIT | V10 | %s\n',upper(runMode));
fprintf('====================================================================\n');

%% Locate package
thisFile=mfilename('fullpath'); if isempty(thisFile), startDir=pwd; else, startDir=fileparts(thisFile); end
projectRoot=locate_original_v10_root(startDir);
if isempty(projectRoot)
    fprintf(2,'Could not automatically find the ORIGINAL V10 root.\n');
    fprintf(2,'Select the folder that DIRECTLY contains the original V10 +aigc folder.\n');
    fprintf(2,'Do NOT select v10_p01_core for Theory-P1.\n');
    selected=uigetdir(pwd,'Select ORIGINAL V10 project root containing +aigc');
    if isequal(selected,0), error('No original V10 project root selected.'); end
    [~,leaf]=fileparts(selected);
    if strcmp(leaf,'+aigc'), selected=fileparts(selected); end
    if ~is_valid_original_v10_root(selected)
        error('Selected folder is not the required ORIGINAL V10 source tree.');
    end
    projectRoot=selected;
end
remove_competing_aigc_roots(projectRoot);
addpath(projectRoot,'-begin'); rehash; clear functions; %#ok<CLFUNC>
addpath(projectRoot,'-begin'); rehash;
validate_theory_v10_source_tree(projectRoot);
required={'default_parameters','default_options','experiment_settings','full_mode','solve_model','model_rhs'};
for k=1:numel(required)
    if exist(fullfile(projectRoot,'+aigc',[required{k} '.m']),'file')~=2
        error('Missing +aigc/%s.m',required{k});
    end
end
warn_if_multiple_package_versions('aigc.model_rhs');

pBase=aigc.default_parameters(); opt=aigc.default_options(runMode); settings=aigc.experiment_settings(runMode); %#ok<NASGU>
[p,parameterSource]=get_R1_parameters_locked(pBase);
mode=aigc.full_mode();
if ~isfield(opt,'X0')||numel(opt.X0)~=10, error('Active V10 opt.X0 must be 10-D.'); end
X0=opt.X0(:);

outputDir=fullfile(projectRoot,'outputs',['Theory_P1_IZ_stability_' CFG.RUN_TAG '_' runMode]);
if ~exist(outputDir,'dir'), mkdir(outputDir); end
diary(fullfile(outputDir,'run_log.txt')); cleanupDiary=onCleanup(@() diary('off')); %#ok<NASGU>

%% Long-run reference state
[solRef,refH]=solve_long_reference(X0,p,mode,opt,CFG.REFERENCE_HORIZON);
idx=tail_index_time(solRef.t,CFG.TAIL_FRACTION);
Xref=time_weighted_vector_mean(solRef.t(idx),solRef.X(idx,:))';
rhsRef=aigc.model_rhs(solRef.t(end),Xref,p,mode); rhsRef=rhsRef(:);
fullResidual=max(abs(rhsRef));

[Jref,refDiag]=jacobian_iz_numeric(Xref,p,mode,CFG.FD_STEP);
Tref=table(Xref(4),Xref(3),Jref(1,1),Jref(1,2),Jref(2,1),Jref(2,2), ...
    trace(Jref),det(Jref),refDiag.CrossSignPass,refDiag.HurwitzPass,fullResidual,refH, ...
    'VariableNames',{'Iref','zref','F_I','F_z','G_I','G_z','Trace','Determinant', ...
    'CrossSignPass','HurwitzPass','FullRHSResidual','ReferenceHorizon'});
writetable(Tref,fullfile(outputDir,'theory_p1_reference_jacobian.csv'));

%% Local grid with all other states frozen at Xref
Ilo=max(CFG.INTERIOR_MARGIN,Xref(4)-CFG.SPAN_I); Ihi=min(1-CFG.INTERIOR_MARGIN,Xref(4)+CFG.SPAN_I);
zlo=max(CFG.INTERIOR_MARGIN,Xref(3)-CFG.SPAN_Z); zhi=min(1-CFG.INTERIOR_MARGIN,Xref(3)+CFG.SPAN_Z);
Igrid=linspace(Ilo,Ihi,CFG.GRID_N); zgrid=linspace(zlo,zhi,CFG.GRID_N);
rows=struct([]); krow=0;
for iz=1:numel(zgrid)
    for ii=1:numel(Igrid)
        X=Xref; X(4)=Igrid(ii); X(3)=zgrid(iz);
        [J,d]=jacobian_iz_numeric(X,p,mode,CFG.FD_STEP);
        q=aigc.model_rhs(0,X,p,mode); q=q(:);
        krow=krow+1;
        r=struct(); r.I=Igrid(ii); r.z=zgrid(iz); r.dotI=q(4); r.dotz=q(3);
        r.F_I=J(1,1); r.F_z=J(1,2); r.G_I=J(2,1); r.G_z=J(2,2);
        r.Trace=trace(J); r.Determinant=det(J); r.CrossSignPass=d.CrossSignPass;
        r.OwnDampingPass=d.OwnDampingPass; r.HurwitzPass=d.HurwitzPass;
        rows=append_struct(rows,r); %#ok<AGROW>
    end
end
T=struct2table(rows);
writetable(T,fullfile(outputDir,'theory_p1_iz_local_grid.csv'));

%% Summary and quality gate
S=table(height(T),mean(T.F_z<0),mean(T.G_I>0),mean(T.CrossSignPass), ...
    mean(T.F_I<0),mean(T.G_z<0),mean(T.OwnDampingPass),mean(T.Trace<0), ...
    mean(T.Determinant>0),mean(T.HurwitzPass), ...
    'VariableNames',{'NGridPoints','Rate_Fz_negative','Rate_GI_positive','Rate_CrossSignPass', ...
    'Rate_FI_negative','Rate_Gz_negative','Rate_OwnDampingPass','Rate_TraceNegative', ...
    'Rate_DeterminantPositive','Rate_HurwitzPass'});
writetable(S,fullfile(outputDir,'theory_p1_iz_summary.csv'));

finiteRef=all(isfinite(Jref(:)));
finiteGrid=all(isfinite(T.F_I))&&all(isfinite(T.F_z))&&all(isfinite(T.G_I))&&all(isfinite(T.G_z));
Q=table(["Finite reference derivatives";"Finite grid derivatives";"Reference cross-feedback signs";"Reference reduced Hurwitz"], ...
    [finiteRef;finiteGrid;refDiag.CrossSignPass;refDiag.HurwitzPass], ...
    [double(finiteRef);double(finiteGrid);double(refDiag.CrossSignPass);double(refDiag.HurwitzPass)], ...
    [1;1;1;1], ...
    'VariableNames',{'Check','Pass','Value','ReferenceThreshold'});
writetable(Q,fullfile(outputDir,'experiment_quality_check.csv'));

save(fullfile(outputDir,'THEORY_P1_IZ_AUDIT.mat'),'CFG','p','mode','opt','Xref','Jref','T','S','Q','parameterSource','-v7.3');
write_report(fullfile(outputDir,'THEORY_P1_IZ_REPORT.txt'),CFG,projectRoot,parameterSource,Tref,S,Q);

if CFG.SHOW_FIGURES
    try
        plot_grid(T,Igrid,zgrid,outputDir);
    catch ME
        warning('Plot failed: %s',ME.message);
    end
end

fprintf('\nReference I=%.6f, z=%.6f\n',Xref(4),Xref(3));
fprintf('F_z=%+.6e, G_I=%+.6e, trace=%+.6e, det=%+.6e\n',Jref(1,2),Jref(2,1),trace(Jref),det(Jref));
fprintf('Grid cross-sign pass: %.2f%% | reduced Hurwitz pass: %.2f%%\n',100*mean(T.CrossSignPass),100*mean(T.HurwitzPass));
fprintf('Output: %s\n',outputDir);
end

%% ======================================================================
function [J,d]=jacobian_iz_numeric(X,p,mode,h)
% Order: rows [dotI,dotz], columns [I,z].
J=zeros(2,2); vars=[4 3]; outs=[4 3];
for c=1:2
    j=vars(c); hp=min(h,0.45*min(max(X(j),h),max(1-X(j),h)));
    hp=max(hp,h*1e-3);
    Xp=X; Xm=X; Xp(j)=min(1-1e-10,X(j)+hp); Xm(j)=max(1e-10,X(j)-hp);
    denom=Xp(j)-Xm(j);
    fp=aigc.model_rhs(0,Xp,p,mode); fm=aigc.model_rhs(0,Xm,p,mode);
    J(:,c)=(fp(outs)-fm(outs))/denom;
end
d=struct(); d.CrossSignPass=(J(1,2)<0)&&(J(2,1)>0); d.OwnDampingPass=(J(1,1)<0)&&(J(2,2)<0); d.HurwitzPass=(trace(J)<0)&&(det(J)>0);
end

function [sol,hUsed]=solve_long_reference(X0,p,mode,opt,H)
% Use one explicit reference horizon for each run mode.  The reference is
% allowed to be a cycle; the reduced sign audit then uses its long-run
% time-mean background and does NOT relabel that mean as a full equilibrium.
o=opt; o.t0=0; o.tEnd=H; o.allowEarlyStop=false; o.solver='ode45';
if isfield(o,'odeRelTol'), o.odeRelTol=min(o.odeRelTol,1e-9); end
if isfield(o,'odeAbsTol'), o.odeAbsTol=min(o.odeAbsTol,1e-11); end
sol=aigc.solve_model(X0,p,mode,o); hUsed=H;
end

function plot_grid(T,Igrid,zgrid,outDir)
ZI=nan(numel(zgrid),numel(Igrid)); ZD=ZI; ZS=ZI;
for k=1:height(T)
    [~,ii]=min(abs(Igrid-T.I(k))); [~,iz]=min(abs(zgrid-T.z(k)));
    ZI(iz,ii)=T.Trace(k); ZD(iz,ii)=T.Determinant(k); ZS(iz,ii)=double(T.CrossSignPass(k));
end
fig=figure('Visible','off','Color','w','Position',[50 50 1450 450]); tl=tiledlayout(1,3,'TileSpacing','compact','Padding','compact');
nexttile; imagesc(Igrid,zgrid,ZI); axis xy; colorbar; xlabel('Risk state I'); ylabel('Vigilant-user fraction z'); title('Reduced trace');
nexttile; imagesc(Igrid,zgrid,ZD); axis xy; colorbar; xlabel('Risk state I'); ylabel('z'); title('Reduced determinant');
nexttile; imagesc(Igrid,zgrid,ZS,[0 1]); axis xy; colorbar; xlabel('Risk state I'); ylabel('z'); title('Cross-sign condition F_z<0, G_I>0');
title(tl,'Frozen-background (I,z) code-to-theory audit');
save_figure_local(fig,outDir,'fig_theory_p1_iz_local_stability');
end

function write_report(fileName,CFG,root,source,Tref,S,Q)
fid=fopen(fileName,'w'); if fid<0, return; end; c=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'Theory-P1 reduced (I,z) stability audit\n======================================\n');
fprintf(fid,'Project root: %s\nParameter source: %s\nRun mode: %s\nReference horizon: %g\n\n',root,source,CFG.RUN_MODE,CFG.REFERENCE_HORIZON);
fprintf(fid,'Reference state\n---------------\n');
fprintf(fid,'I=%.8f, z=%.8f\n',Tref.Iref,Tref.zref);
fprintf(fid,'F_I=%+.8e, F_z=%+.8e, G_I=%+.8e, G_z=%+.8e\n',Tref.F_I,Tref.F_z,Tref.G_I,Tref.G_z);
fprintf(fid,'trace=%+.8e, determinant=%+.8e\n',Tref.Trace,Tref.Determinant);
fprintf(fid,'Cross-sign pass=%d; reduced Hurwitz pass=%d\n\n',Tref.CrossSignPass,Tref.HurwitzPass);
fprintf(fid,'Local grid prevalence\n---------------------\n');
fprintf(fid,'F_z<0: %.3f%%\n',100*S.Rate_Fz_negative); fprintf(fid,'G_I>0: %.3f%%\n',100*S.Rate_GI_positive);
fprintf(fid,'cross-sign: %.3f%%\n',100*S.Rate_CrossSignPass); fprintf(fid,'trace<0: %.3f%%\n',100*S.Rate_TraceNegative);
fprintf(fid,'det>0: %.3f%%\n',100*S.Rate_DeterminantPositive); fprintf(fid,'2-D Hurwitz: %.3f%%\n\n',100*S.Rate_HurwitzPass);
fprintf(fid,'Interpretation\n--------------\n');
fprintf(fid,['This audit tests the reduced frozen-background feedback directly on the active V10 RHS. ', ...
    'A positive result supports a local stabilizing risk-vigilance loop; it does not imply full 10-D stability. ', ...
    'Full-system oscillations may still arise through slow/adaptive states and their phase lags.\n\n']);
fprintf(fid,'Quality gate\n------------\n'); for i=1:height(Q), fprintf(fid,'%s: %d (value %.4f)\n',char(Q.Check(i)),Q.Pass(i),Q.Value(i)); end
end

