function root=locate_original_v10_root(startDir)
root=''; C={}; bases={startDir,pwd};
for b=1:numel(bases)
    c=bases{b};
    for u=1:8
        if isempty(c), break; end
        C{end+1}=c; %#ok<AGROW>
        C{end+1}=fullfile(c,'v10_core'); %#ok<AGROW>
        C{end+1}=fullfile(c,'AIGC_Coevolution_V10'); %#ok<AGROW>
        C{end+1}=fullfile(c,'v10_core','AIGC_Coevolution_V10'); %#ok<AGROW>
        c2=fileparts(c); if strcmp(c2,c), break; end; c=c2;
    end
end
probe=which('aigc.default_parameters');
if ~isempty(probe), C{end+1}=fileparts(fileparts(probe)); end %#ok<AGROW>
for k=1:numel(C)
    if is_valid_original_v10_root(C{k}), root=C{k}; return; end
end
end

function tf=is_valid_original_v10_root(root)
tf=false;
if isempty(root)||exist(root,'dir')~=7, return; end
pkg=fullfile(root,'+aigc');
if exist(pkg,'dir')~=7, return; end
req={'default_parameters.m','default_options.m','experiment_settings.m','full_mode.m','solve_model.m','model_rhs.m'};
for k=1:numel(req), if exist(fullfile(pkg,req{k}),'file')~=2, return; end, end
if exist(fullfile(pkg,'exp06_timescale_causal_audit.m'),'file')==2 && exist(fullfile(pkg,'exp08_nested_policy_comparison.m'),'file')==2
    return;
end
tf=true;
end

function validate_theory_v10_source_tree(root)
if ~is_valid_original_v10_root(root), error('Theory-P1 source-lineage check failed: use original V10, not V10-P0.1.'); end
pkg=fullfile(root,'+aigc');
E={{'aigc.default_parameters','default_parameters.m'},{'aigc.default_options','default_options.m'}, ...
   {'aigc.experiment_settings','experiment_settings.m'},{'aigc.full_mode','full_mode.m'}, ...
   {'aigc.solve_model','solve_model.m'},{'aigc.model_rhs','model_rhs.m'}};
for k=1:numel(E)
    resolved=which(E{k}{1}); target=fullfile(pkg,E{k}{2});
    if isempty(resolved)||~same_path_local(resolved,target)
        error('MATLAB path conflict for %s.\nResolved: %s\nExpected: %s',E{k}{1},resolved,target);
    end
end
fprintf('Theory-P1 ORIGINAL V10 source-lineage check: PASS\n');
end

function remove_competing_aigc_roots(selectedRoot)
funcs={'aigc.default_parameters','aigc.solve_model','aigc.model_rhs'}; roots={};
for i=1:numel(funcs)
    h=which(funcs{i},'-all'); if ischar(h), h={h}; end
    for j=1:numel(h), roots{end+1}=fileparts(fileparts(h{j})); end %#ok<AGROW>
end
if isempty(roots), return; end
roots=unique(roots,'stable');
for k=1:numel(roots)
    r=roots{k};
    if ~strcmpi(normalize_path_local(r),normalize_path_local(selectedRoot))
        try, rmpath(r); fprintf('[PATH] Removed competing AIGC root: %s\n',r); catch, end
    end
end
rehash;
end

function tf=same_path_local(a,b), tf=strcmpi(normalize_path_local(a),normalize_path_local(b)); end
function p=normalize_path_local(p)
p=char(p); try, p=char(java.io.File(p).getCanonicalPath()); catch, end
p=strrep(p,'/',filesep); while numel(p)>1&&p(end)==filesep, p(end)=[]; end
end

function warn_if_multiple_package_versions(fn), h=which(fn,'-all'); if ischar(h),h={h};end; if numel(h)>1,fprintf(2,'WARNING: multiple %s versions on path.\n',fn);for k=1:numel(h),fprintf(2,'  %s\n',h{k});end,end,end
